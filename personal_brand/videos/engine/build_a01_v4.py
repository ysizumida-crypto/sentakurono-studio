# ---- sec9 を三部構成で再合成(祝詞: 0.82速・句間1.4・音量1.08) ----
sec9wav = f'{WD}/segs/sec09.wav'
if not os.path.exists(sec9wav):
    p1 = "ここからは、開運祈願の時間です。導きのやたがらす、くろのんが、画面のむこうのあなたへ、祈りをおくります。まずは、よどんだ流れを、はらいましょう。"
    p2 = "はらいたまえ、きよめたまえ、まもりたまい、さきわえたまえ。"
    p3 = "あなたにまとわりつく、わるい流れが、しずかに、ほどけていきます。そして。あなたの努力が、めぐりめぐって、実をむすびますように。世界のどこかで、あなたの挑戦が、うまくいきますように。あなたの金運の扉が、しずかに、ひらきますように。"
    E.synth(p1, f'{WD}/segs/s9a.wav', speed=1.15)
    E.synth(p2, f'{WD}/segs/s9b.wav', speed=0.82, pause=1.4, vol=1.08)
    E.synth(p3, f'{WD}/segs/s9c.wav', speed=1.15)
    out = wave.open(sec9wav, 'wb'); first = True
    for fn, gap in ((f'{WD}/segs/s9a.wav', 0.5), (f'{WD}/segs/s9b.wav', 0.7), (f'{WD}/segs/s9c.wav', 0.0)):
        w = wave.open(fn)
        if first:
            out.setparams(w.getparams()); first = False
        out.writeframes(w.readframes(w.getnframes()))
        out.writeframes(b'\x00' * int(gap * w.getframerate() * w.getsampwidth()))
        w.close()
    out.close()
    print('sec9 slow-norito synthesized', flush=True)

