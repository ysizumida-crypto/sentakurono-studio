    p1 = "ここからは、開運祈願の時間です。導きのやたがらす、くろのんが、あなたを、あぶない流れから、まもります。まずは、まよいと、あせりを、はらいましょう。"
    p2 = "はらいたまえ、きよめたまえ、まもりたまい、さきわえたまえ。"
    p3 = "あなたの目が、くもりなく、真実を見ぬけますように。そして。あなたの大切なお金と、時間が、まもられますように。よい出会いだけが、あなたのもとに、のこりますように。"
    E.synth(p1, f'{WD}/segs/s10a.wav', speed=1.15)
    E.synth(p2, f'{WD}/segs/s10b.wav', speed=0.82, pause=1.4, vol=1.08)
    E.synth(p3, f'{WD}/segs/s10c.wav', speed=1.15)
    out = wave.open(sec10wav, 'wb'); first = True
    for fn, gap in ((f'{WD}/segs/s10a.wav', 0.5), (f'{WD}/segs/s10b.wav', 0.7), (f'{WD}/segs/s10c.wav', 0.0)):
        w = wave.open(fn)
        if first: out.setparams(w.getparams()); first = False
        out.writeframes(w.readframes(w.getnframes()))
        out.writeframes(b'\x00' * int(gap * w.getframerate() * w.getsampwidth()))
        w.close()
    out.close()
    print('a03 sec10 slow-norito synthesized', flush=True)

